#!/bin/sh
# The format of what Blend writes (`blend-stamps`): blend.bend's hash,
# written into blend_stamp.bend, which blend.bend imports. Every change to
# blend.bend moves it, erring toward too many updates: a file Blend wrote
# is current only for the Blend that wrote it. blend_stamp.bend is generated,
# never edited; the pre-commit hook writes and stages it for blend.bend
# as staged, and the gate (check_generated.sh) checks it.
#
#   blend_stamp.sh            write blend_stamp.bend for blend.bend as it is
#   blend_stamp.sh --staged   for blend.bend as staged, and stage it
#   blend_stamp.sh --check    whether blend_stamp.bend is blend.bend's
set -u
cd "$(dirname "$0")" || exit 1
sum() { { sha256sum 2>/dev/null || shasum -a 256; } | cut -c1-12; }
case ${1:-} in
  --staged) h=$(git show :./blend.bend | sum) ;;
  *) h=$(sum < blend.bend) ;;
esac
[ -n "$h" ] || { echo "blend_stamp.sh: no hash of blend.bend" >&2; exit 1; }
want=$(printf '%s\n' 'import Base' '' \
  "# blend.bend's hash, the format of what Blend writes (blend-stamps):" \
  '# generated by blend_stamp.sh, never edited' \
  'def hash() -> String:' "  \"$h\"")
have=$(cat blend_stamp.bend 2>/dev/null)
case ${1:-} in
  --check)
    [ "$have" = "$want" ] && exit 0
    echo "blend_stamp.bend is not blend.bend's hash, $h: run ./blend_stamp.sh (the pre-commit hook does)"
    exit 1 ;;
  *)
    [ "$have" = "$want" ] || printf '%s\n' "$want" > blend_stamp.bend || exit 1
    [ "${1:-}" = --staged ] && { git add blend_stamp.bend || exit 1; }
    exit 0 ;;
esac
